// Usage: node scout.mjs <outDir> — stills of the ADME surface on the sample stage.
import { createRequire } from "node:module";
const { chromium } = createRequire(new URL("../../../tools/", import.meta.url))("playwright");
import { mkdirSync } from "node:fs";
const [OUT = "../raw/scout"] = process.argv.slice(2);
mkdirSync(OUT, { recursive: true });
const b = await chromium.launch({ channel: "chrome" });
const ctx = await b.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1.2, colorScheme: "dark" });
const p = await ctx.newPage();
await p.goto("http://127.0.0.1:7980/", { waitUntil: "networkidle" });
await p.screenshot({ path: `${OUT}/00-home.png` });
const shot = async (name, wait = 900) => { await p.waitForTimeout(wait); await p.screenshot({ path: `${OUT}/${name}.png` }); };
await p.getByText("ADME", { exact: true }).first().click();
await shot("01-access", 1800);
await p.mouse.wheel(0, 700); await shot("02-access-scroll");
await p.mouse.wheel(0, 900); await shot("03-access-scroll2");
await p.mouse.wheel(0, -3000);
await p.getByRole("button", { name: /Rachel Kim/ }).first().click();
await shot("04-rachel", 1500);
await p.getByRole("button", { name: "Why 401/403" }).first().click().catch((e) => console.log("why", e.message));
await shot("05-why401", 1500);
await p.keyboard.press("Escape");
await p.getByRole("button", { name: /^Data/ }).first().click().catch((e) => console.log("data", e.message));
await shot("06-data", 1800);
await p.mouse.wheel(0, 800); await shot("07-data-scroll");
await p.mouse.wheel(0, -3000);
await p.getByRole("button", { name: /^Seismic/ }).first().click().catch((e) => console.log("seis", e.message));
await shot("08-seismic", 1200);
await p.getByRole("button", { name: "Read subprojects" }).first().click().catch((e) => console.log("read", e.message));
await shot("09-seismic-read", 2000);
await p.mouse.wheel(0, 800); await shot("10-seismic-scroll");
await b.close();
