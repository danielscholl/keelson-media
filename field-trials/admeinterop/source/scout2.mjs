import { createRequire } from "node:module";
const { chromium } = createRequire(new URL("../../../tools/", import.meta.url))("playwright");
const OUT = "../raw/scout";
const b = await chromium.launch({ channel: "chrome" });
const ctx = await b.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1.2, colorScheme: "dark" });
const p = await ctx.newPage();
await p.goto("http://127.0.0.1:7980/", { waitUntil: "networkidle" });
await p.getByText("ADME", { exact: true }).first().click();
await p.waitForTimeout(1500);
await p.getByRole("button", { name: /^Seismic/ }).first().click();
await p.waitForTimeout(800);
await p.getByRole("button", { name: "Read subprojects" }).first().click().catch(() => {});
await p.waitForTimeout(2000);
await p.mouse.wheel(0, 800); await p.waitForTimeout(600);
const sel = p.locator("select").nth(0);
console.log(await sel.locator("option").allInnerTexts());
await sel.selectOption({ label: "Lena Fischer" });
await p.getByRole("button", { name: "Preview plan" }).first().click();
await p.waitForTimeout(2500);
await p.screenshot({ path: `${OUT}/s3-plan.png` });
await b.close();
