import { chromium } from "playwright";
import { mkdirSync, writeFileSync, rmSync } from "node:fs";
const OUT = process.argv[2]; rmSync(OUT, { recursive: true, force: true }); mkdirSync(OUT + "/frames", { recursive: true });
const CURSOR = `
(() => { if (window.__cur) return; const add = () => {
  const c = document.createElement('div'); window.__cur = c;
  c.innerHTML = '<svg width="28" height="28" viewBox="0 0 24 24"><path d="M4 2 L4 20 L9 15 L12.5 22 L15.5 20.5 L12 13.8 L19 13.8 Z" fill="white" stroke="#0d1429" stroke-width="1.4" stroke-linejoin="round"/></svg>';
  Object.assign(c.style, { position:'fixed', left:'0', top:'0', zIndex:2147483647, pointerEvents:'none', transform:'translate(800px,520px)', filter:'drop-shadow(0 2px 3px rgba(0,0,0,.5))' });
  document.body.appendChild(c);
  document.addEventListener('mousemove', e => { c.style.transform = 'translate(' + (e.clientX-4) + 'px,' + (e.clientY-2) + 'px)'; }, true);
  document.addEventListener('mousedown', e => { const r = document.createElement('div');
    Object.assign(r.style, { position:'fixed', left:(e.clientX-18)+'px', top:(e.clientY-18)+'px', width:'36px', height:'36px', borderRadius:'50%', border:'3px solid #9b8eff', zIndex:2147483646, pointerEvents:'none', transition:'all .45s ease-out', opacity:'1' });
    document.body.appendChild(r); requestAnimationFrame(() => { r.style.transform='scale(1.8)'; r.style.opacity='0'; }); setTimeout(() => r.remove(), 600); }, true);
}; document.readyState === 'loading' ? document.addEventListener('DOMContentLoaded', add) : add(); })();`;
const b = await chromium.launch({ channel: "chrome" });
const ctx = await b.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1.2, colorScheme: "dark" });
await ctx.addInitScript(`try { localStorage.setItem("keelson.activeProjectId", "771a230a-c882-4c66-845b-70e55c54eee3"); } catch {}`);
await ctx.addInitScript(CURSOR);
const p = await ctx.newPage();
await p.goto("http://127.0.0.1:7979/", { waitUntil: "networkidle" });
await p.getByText("Workflows", { exact: true }).first().click();
await p.getByRole("radio", { name: "Workflows" }).click();
await p.mouse.move(800, 520);
await p.waitForTimeout(800);
const frames = []; const marks = {};
const cdp = await ctx.newCDPSession(p);
cdp.on("Page.screencastFrame", async f => { const i = frames.length; frames.push(f.metadata.timestamp);
  writeFileSync(`${OUT}/frames/${String(i).padStart(5,"0")}.jpg`, Buffer.from(f.data, "base64"));
  await cdp.send("Page.screencastFrameAck", { sessionId: f.sessionId }).catch(() => {}); });
const mark = k => { marks[k] = Date.now() / 1000; };
const glide = async (loc, ms = 700) => { const bb = await loc.boundingBox(); const x = bb.x + bb.width/2, y = bb.y + bb.height/2; await p.mouse.move(x, y, { steps: Math.round(ms/16) }); return { x, y }; };
await cdp.send("Page.startScreencast", { format: "jpeg", quality: 92, maxWidth: 1920, maxHeight: 1080, everyNthFrame: 1 });
mark("start");
await p.waitForTimeout(1200);
const search = p.getByPlaceholder("Search workflows");
await glide(search); mark("search"); await search.click(); await p.waitForTimeout(200);
await search.pressSequentially("smoke", { delay: 110 });
await p.waitForTimeout(900);
const run = p.getByRole("button", { name: /Run/ }).first();
await glide(run, 900); await p.waitForTimeout(250); mark("run"); await run.click();
await p.waitForTimeout(1300);
const start = p.getByRole("button", { name: "Start", exact: true });
await glide(start, 800); await p.waitForTimeout(200); mark("start-click"); await start.click();
await p.getByText("completed", { exact: true }).first().waitFor({ timeout: 60000 }); mark("done");
await p.waitForTimeout(1500);
await p.mouse.move(700, 600, { steps: 40 }); mark("expand");
await p.waitForTimeout(3000);
await p.screenshot({ path: `${OUT}/expanded.png` });
const back = p.getByRole("button", { name: "Back to catalog" });
const runsRadio = p.getByRole("radio", { name: "Runs" });
await glide(back, 800); mark("back"); await back.click();
await p.waitForTimeout(500);
await glide(runsRadio, 700); mark("runs"); await runsRadio.click();
await p.waitForTimeout(4000); mark("end");
await p.screenshot({ path: `${OUT}/runs.png` });
await cdp.send("Page.stopScreencast");
await p.waitForTimeout(300);
writeFileSync(`${OUT}/meta.json`, JSON.stringify({ frames, marks }, null, 1));
console.log("frames", frames.length, "marks", JSON.stringify(Object.fromEntries(Object.entries(marks).map(([k, v]) => [k, +(v - marks.start).toFixed(2)]))));
await b.close();
