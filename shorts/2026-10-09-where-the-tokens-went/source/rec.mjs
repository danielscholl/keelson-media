// Usage: node rec.mjs <outDir>
import { chromium } from "playwright";
import { mkdirSync, writeFileSync, rmSync, readFileSync } from "node:fs";
const [OUT] = process.argv.slice(2);
rmSync(OUT, { recursive: true, force: true }); mkdirSync(OUT + "/frames", { recursive: true });
const CURSOR = readFileSync(new URL("../../../tools/cursor.js", import.meta.url), "utf8");
const b = await chromium.launch({ channel: "chrome" });
const ctx = await b.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1.2, colorScheme: "dark" });
await ctx.addInitScript(CURSOR);
const p = await ctx.newPage();
await p.goto("http://127.0.0.1:7979/", { waitUntil: "networkidle" });
await p.mouse.move(900, 500);
await p.waitForTimeout(800);
const frames = []; const marks = {};
const cdp = await ctx.newCDPSession(p);
cdp.on("Page.screencastFrame", async f => { const i = frames.length; frames.push(f.metadata.timestamp);
  writeFileSync(`${OUT}/frames/${String(i).padStart(5,"0")}.jpg`, Buffer.from(f.data, "base64"));
  await cdp.send("Page.screencastFrameAck", { sessionId: f.sessionId }).catch(() => {}); });
const mark = k => { marks[k] = Date.now() / 1000; };
const glide = async (loc, ms = 700) => { const bb = await loc.boundingBox(); await p.mouse.move(bb.x + bb.width/2, bb.y + bb.height/2, { steps: Math.round(ms/16) }); };
const scroll = async (dy, steps = 14) => { for (let i = 0; i < steps; i++) { await p.mouse.wheel(0, dy / steps); await p.waitForTimeout(35); } };
await cdp.send("Page.startScreencast", { format: "jpeg", quality: 92, maxWidth: 1920, maxHeight: 1080, everyNthFrame: 1 });
mark("start");
await p.waitForTimeout(1000);
const gear = p.locator("button.instruments-trigger");
await glide(gear, 900); await p.waitForTimeout(200); await gear.click(); await p.waitForTimeout(500);
const us = p.getByRole("button", { name: /^Usage/ });
await glide(us, 500); await p.waitForTimeout(200); mark("usage"); await us.click();
await p.waitForTimeout(5500); mark("ribbon");
await p.mouse.move(900, 600, { steps: 20 });
await scroll(1100, 20); await p.waitForTimeout(4500);
const costBtns = p.getByText("Cost", { exact: true });
const n = await costBtns.count();
await glide(costBtns.nth(n - 1), 700); await p.waitForTimeout(200); mark("cost"); await costBtns.nth(n - 1).click();
await p.waitForTimeout(400);
await p.mouse.move(900, 600, { steps: 10 });
await scroll(1200, 12); mark("costview");
await p.waitForTimeout(4500);
await scroll(-1200, 10); await p.waitForTimeout(600);
const models = p.getByText("Models", { exact: true }).first();
await glide(models, 700); await p.waitForTimeout(200); mark("models"); await models.click();
await p.waitForTimeout(5500);
const jobs = p.getByText("Jobs", { exact: true }).first();
await glide(jobs, 700); await p.waitForTimeout(200); mark("jobs"); await jobs.click();
await p.waitForTimeout(4500);
const led = p.getByText("Ledger", { exact: true }).first();
await glide(led, 700); await p.waitForTimeout(200); mark("ledger"); await led.click();
await p.waitForTimeout(2500);
const cell = p.getByText(/^\$0\.0[0-9]+$/).first();
await glide(cell, 800); mark("hover"); await p.waitForTimeout(3500);
mark("end");
await cdp.send("Page.stopScreencast");
writeFileSync(`${OUT}/meta.json`, JSON.stringify({ frames, marks }, null, 1));
await p.screenshot({ path: `${OUT}/last.png` });
console.log("frames", frames.length, JSON.stringify(Object.fromEntries(Object.entries(marks).map(([k, v]) => [k, +(v - marks.start).toFixed(2)]))));
await b.close().catch(() => {}); process.exit(0);
