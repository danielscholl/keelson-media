// Usage: node rec-launch.mjs <outDir> — fills the launcher (Fleet, factory mode, cosmos-factory, write, tracker) and starts the swarm.
import { chromium } from "playwright";
import { mkdirSync, writeFileSync, rmSync, readFileSync } from "node:fs";
const [OUT] = process.argv.slice(2);
rmSync(OUT, { recursive: true, force: true }); mkdirSync(OUT + "/frames", { recursive: true });
const CURSOR = readFileSync(new URL("../../../../tools/cursor.js", import.meta.url), "utf8");
const TASK = readFileSync(new URL("./task.txt", import.meta.url), "utf8");
const b = await chromium.launch({ channel: "chrome" });
const ctx = await b.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1.2, colorScheme: "dark" });
const p = await ctx.newPage();
await p.addInitScript(CURSOR);
await p.goto("http://127.0.0.1:7979/", { waitUntil: "networkidle" });
await p.getByText("Swarms", { exact: true }).first().click(); await p.waitForTimeout(2500);
const f = p.frames()[1];
await f.evaluate(() => { if (window.__cur) window.__cur.remove(); });
await p.mouse.move(900, 500); await p.waitForTimeout(600);
const frames = []; const marks = {};
const cdp = await ctx.newCDPSession(p);
cdp.on("Page.screencastFrame", async fr => { const i = frames.length; frames.push(fr.metadata.timestamp);
  writeFileSync(`${OUT}/frames/${String(i).padStart(5,"0")}.jpg`, Buffer.from(fr.data, "base64"));
  await cdp.send("Page.screencastFrameAck", { sessionId: fr.sessionId }).catch(() => {}); });
const mark = k => { marks[k] = Date.now() / 1000; };
const glide = async (loc, ms = 700) => { const bb = await loc.boundingBox(); await p.mouse.move(bb.x + bb.width/2, bb.y + bb.height/2, { steps: Math.round(ms/16) }); };
const clickIt = async (loc, k, ms = 700) => { await loc.scrollIntoViewIfNeeded(); await glide(loc, ms); await p.waitForTimeout(200); mark(k); await loc.click(); await p.waitForTimeout(500); };
await cdp.send("Page.startScreencast", { format: "jpeg", quality: 92, maxWidth: 1920, maxHeight: 1080, everyNthFrame: 1 });
mark("start"); await p.waitForTimeout(800);
const ta = f.locator("#launch-task");
await glide(ta, 800); await ta.click(); mark("paste"); await ta.fill(TASK); await ta.evaluate(e => e.scrollTop = 0); await p.waitForTimeout(2500);
await clickIt(f.locator("#plan-large"), "fleet");
await clickIt(f.locator("#launch-factory"), "factory");
const ps = f.locator("#launch-project"); await ps.scrollIntoViewIfNeeded(); await glide(ps, 700); mark("project");
await ps.selectOption({ index: 1 }); await p.waitForTimeout(900);
await clickIt(f.locator("#allow-write"), "write");
await clickIt(f.locator("#allow-tracker"), "tracker");
const st = f.locator("#launch-start"); await st.scrollIntoViewIfNeeded(); await glide(st, 800); mark("summary"); await p.waitForTimeout(3000);
mark("startclick"); await st.click();
await p.waitForTimeout(25000); mark("end");
await cdp.send("Page.stopScreencast");
writeFileSync(`${OUT}/meta.json`, JSON.stringify({ frames, marks }, null, 1));
await p.screenshot({ path: `${OUT}/last.png` });
console.log("frames", frames.length, JSON.stringify(Object.fromEntries(Object.entries(marks).map(([k, v]) => [k, +(v - marks.start).toFixed(2)]))));
await b.close().catch(() => {}); process.exit(0);
