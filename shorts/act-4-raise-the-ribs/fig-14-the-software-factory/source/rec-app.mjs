// Usage: node rec-app.mjs <outDir> — a take of the Cosmos app the factory built, served by bun on :3000.
import { chromium } from "playwright";
import { mkdirSync, writeFileSync, rmSync, readFileSync } from "node:fs";
const [OUT] = process.argv.slice(2);
rmSync(OUT, { recursive: true, force: true }); mkdirSync(OUT + "/frames", { recursive: true });
const CURSOR = readFileSync(new URL("../../../../tools/cursor.js", import.meta.url), "utf8");
const b = await chromium.launch({ channel: "chrome" });
const ctx = await b.newContext({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1.2 });
await ctx.addInitScript("if (window.top === window) {" + CURSOR + "}");
const p = await ctx.newPage();
await p.goto("http://localhost:3000/", { waitUntil: "networkidle" });
await p.mouse.move(1300, 700);
await p.waitForTimeout(800);
const frames = []; const marks = {};
const cdp = await ctx.newCDPSession(p);
cdp.on("Page.screencastFrame", async f => { const i = frames.length; frames.push(f.metadata.timestamp);
  writeFileSync(`${OUT}/frames/${String(i).padStart(5,"0")}.jpg`, Buffer.from(f.data, "base64"));
  await cdp.send("Page.screencastFrameAck", { sessionId: f.sessionId }).catch(() => {}); });
const mark = k => { marks[k] = Date.now() / 1000; };
const glide = async (loc, ms = 700) => { const bb = await loc.boundingBox(); await p.mouse.move(bb.x + bb.width/2, bb.y + bb.height/2, { steps: Math.round(ms/16) }); };
await cdp.send("Page.startScreencast", { format: "jpeg", quality: 92, maxWidth: 1920, maxHeight: 1080, everyNthFrame: 1 });
mark("start");
await p.waitForTimeout(3500);
const ex = p.getByRole("link", { name: /Explore the collection/ });
await glide(ex, 900); await p.waitForTimeout(250); mark("explore"); await ex.click();
await p.waitForTimeout(2500);
const planet = p.getByRole("button", { name: /^Planet/ });
await glide(planet, 800); await p.waitForTimeout(250); mark("filter"); await planet.click();
await p.waitForTimeout(2500);
const sat = p.locator('a[href="/objects/saturn"]').first();
await glide(sat, 900); await p.waitForTimeout(400); mark("saturn"); await sat.click();
await p.waitForLoadState("networkidle"); await p.waitForTimeout(3500);
mark("detail");
await p.mouse.wheel(0, 450); await p.waitForTimeout(2200);
const chill = p.getByRole("button", { name: /chill/i }).first();
if (await chill.count()) { await chill.scrollIntoViewIfNeeded(); await p.waitForTimeout(600); await glide(chill, 800); await p.waitForTimeout(300); mark("chills"); await chill.click(); }
await p.waitForTimeout(3000);
mark("end");
await cdp.send("Page.stopScreencast");
writeFileSync(`${OUT}/meta.json`, JSON.stringify({ frames, marks }, null, 1));
await p.screenshot({ path: `${OUT}/last.png` });
console.log("frames", frames.length, JSON.stringify(Object.fromEntries(Object.entries(marks).map(([k, v]) => [k, +(v - marks.start).toFixed(2)]))));
await b.close().catch(() => {}); process.exit(0);
